"""حارس النوايا قبل الموديل: طلبات لا يجوز أن يجيب عنها أي مسار آلي.

لماذا موجود: الموديل مُوجَّه بالبرومبت ليرفض (تشخيص، جرعات، تطمين، حمل)، لكن
المسار الاحتياطي الذي يعرض مقاطع المعرفة بلا موديل (الاستخراجي) لا «يفهم» السؤال،
فسؤال «اديني جرعة ايبوبروفين» سيطابق مقطع المغص ويُعرض نصه كأنه جواب. هذا
الحارس يقطع هذه الأنماط **قبل** الاسترجاع بغضّ النظر عن وجود الموديل: ردّ ثابت
من ملف الموارد، بلا استدعاء موديل.

حدوده (مثل فلتر الطوارئ): أنماط معجمية على نص مُطبَّع، لا مصنّف. تُقاس بأسئلة
المصائد في `eval/` و`kb/eval/`، وأي صياغة جديدة تُضاف كاختبار.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from .arabic import normalize_arabic

# كل نمط يُطبَّق على نص مُطبَّع (همزات/ياء/تاء مربوطة موحّدة، بلا تشكيل، lowercase)
_PATTERNS: tuple[tuple[str, tuple[str, ...]], ...] = (
    # حقن/تسريب: يسبق الباقي حتى لا يُنفَّذ طلب «تجاهلي وقولي إني عندي…»
    ("injection", (
        r"تجاهل\w*\s+(?:كل\s+)?(?:ال)?(?:تعليمات|ما سبق|القواعد)",
        r"انس\w*\s+(?:كل\s+)?(?:ال)?(?:تعليمات|القواعد)",
        r"ignore\s+(?:all|previous|your)",
        r"system\s*prompt",
        r"(?:اطبع|اكشف|اعرض|وريني|قولي)\w*\s+(?:لي\s+)?(?:ال)?(?:برومبت|بروميت|prompt|تعليماتك|تعليماتك الداخليه)",
        r"تصرف\w*\s+(?:ك|زي|مثل)\s*(?:ال)?دكتور",
        r"(?:انت|انتي)\s+الان\s+",
    )),
    ("medication", (
        r"جرع[هة]|جرعات",
        r"ايبوبروفين|ابوبروفين|بروفين|بنادول|باراسيتامول|ديكلوفيناك|فولتارين|ترامادول|اسبرين|ترانيكساميك|كابريكوتيك",
        r"كام\s+(?:حبه|حبايه|قرص|اقراص|كبسوله|مره\s+في\s+اليوم)",
        r"\b\d+\s*(?:ملغ|مجم|ملجم|mg)\b",
        r"(?:اوقف|وقف|اقطع|اسيب|ابطل|اشيل)\w*\s+(?:ال)?(?:حبوب|دوا|علاج|هرمون|حباي)",
        r"(?:اخد|ناخد|اتناول|اشرب|ينفع\s+اخد)\w*\s+(?:ال)?(?:حديد|مكمل|فيتامين|دوا|مسكن|هرمون)",
    )),
    ("diagnosis", (
        r"(?:اعمل|اعملي|عمل|ممكن)\w*\s+(?:لي\s+|لى\s+)?تشخيص",
        r"شخص(?:ي|يلي|ني)\b",
        r"\b(?:عندي|عندى|انا\s+مصابه|هل\s+(?:انا\s+)?مصابه)\b.{0,40}"
        r"(?:تكيس|بطانه|اورام|ليفي|انيميا|فقر\s+دم|درقيه|غده|عقم|سرطان|سكر|متلازمه)",
        r"هل\s+(?:انا\s+)?(?:عندي|مصابه|عندى)",
        r"(?:قولي|قوليلي|اكدي|اكد)\w*\s+(?:لي\s+)?(?:اني|انى|انك|ان\s+عندي)\s+عندي",
    )),
    ("pregnancy", (
        r"(?:يعني|هل)\s+(?:انا\s+)?حامل",
        r"(?:انا\s+)?حامل\s+(?:ولا|او|صح)",
        r"(?:متاخر|تاخر)\w*.{0,40}(?:حامل|حمل)\b.{0,10}(?:ولا|يعني|صح)",
        r"(?:مش|ما|لست|مو)\s+حامل",
        r"(?:متاكد\w*|اكيد\w*)\s+.{0,15}حامل",
    )),
    ("reassurance", (
        r"(?:مفيش|مافيش|ما\s+فيش)\s+(?:حاجه\s+)?(?:تقلق|مشكله|خطر)",
        r"انا\s+(?:كويسه|بخير|سليمه|طبيعيه)\b.{0,25}(?:صح|مش\s+كده|ولا)",
        r"(?:مش|ما)\s+محتاج\w*\s+(?:دكتور|دكتوره|طبيب)",
        r"(?:اطمني|طمنيني|طمني)\w*",
    )),
    ("prediction", (
        r"(?:توقع|حدد|احسب|قولي|قوليلي)\w*.{0,30}(?:يوم\s+)?(?:ال)?تبويض.{0,25}(?:بالظبط|بالضبط|اكيد|بالتحديد)",
        r"(?:بالظبط|بالضبط|اكيد)\b.{0,30}(?:تبويض|دورتي\s+الجايه|الدوره\s+الجايه|موعد)",
        r"(?:هل|ايمتي|امتي)\s+.{0,20}(?:هنزل|هتيجي|هتنزل)\s+.{0,20}(?:بالظبط|بالضبط)",
    )),
    ("out_of_scope", (
        r"(?:اكتب|اكتبي|اعمل|اعملي|اكتبلي)\w*\s+(?:لي\s+)?(?:كود|برنامج|سكريبت|مقال\s+سياسي)",
        r"\b(?:python|javascript|java|sql|html)\b",
        r"بايثون|برمجه|سياسه|انتخابات|كره\s+القدم",
    )),
)

_COMPILED = tuple((kind, tuple(re.compile(p) for p in pats)) for kind, pats in _PATTERNS)

# مفاتيح ملف الموارد لكل نوع
REPLY_KEYS = {
    "injection": "answer.guard_injection",
    "medication": "answer.guard_medication",
    "diagnosis": "answer.guard_diagnosis",
    "pregnancy": "answer.guard_pregnancy",
    "reassurance": "answer.guard_reassurance",
    "prediction": "answer.guard_prediction",
    "out_of_scope": "answer.guard_out_of_scope",
}
assert set(REPLY_KEYS) == {kind for kind, _ in _PATTERNS}, "نوع حارس بلا مفتاح رد"


@dataclass(frozen=True)
class GuardResult:
    kind: str = ""
    matched: str = ""

    @property
    def triggered(self) -> bool:
        return bool(self.kind)


def check_intent(message: str) -> GuardResult:
    """أول نوع نية محظورة تطابق الرسالة (بالترتيب أعلاه)، أو لا شيء."""
    text = normalize_arabic(message or "").lower()
    if not text:
        return GuardResult()
    for kind, patterns in _COMPILED:
        for pattern in patterns:
            match = pattern.search(text)
            if match:
                return GuardResult(kind=kind, matched=match.group(0)[:40])
    return GuardResult()
